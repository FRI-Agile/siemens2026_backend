namespace RecruitmentModule.Domain.Entity;

/// <summary>
/// One person's application to one job post (<c>recruitment.application</c>, <i>žiadosť</i>): who applied, as they filled
/// in the form, and where the application is in the hiring pipeline.
/// </summary>
/// <remarks>
/// Each job post has its own applicants; there is no shared candidate (ADR-D010), so someone applying to two posts is two
/// unrelated rows. Submitted by the anonymous applicant, so there is no <c>created_by</c> (ADR-D008).
/// </remarks>
public sealed class Application
{
    public Guid Id { get; set; }

    public Guid JobPostId { get; set; }

    public string FirstName { get; set; } = string.Empty;

    public string LastName { get; set; } = string.Empty;

    /// <summary><c>first_name || ' ' || last_name</c>, generated by the database for the name search; never written.</summary>
    public string DisplayName { get; private set; } = string.Empty;

    /// <summary>One application per e-mail and post, without regard to case.</summary>
    public string Email { get; set; } = string.Empty;

    /// <summary>E.164, e.g. <c>+421905123456</c>; optional on the application form.</summary>
    public string? PhoneNumber { get; set; }

    /// <summary>One of <see cref="ApplicationStatuses"/>.</summary>
    public string Status { get; set; } = ApplicationStatuses.New;

    public List<ApplicationDocument> Documents { get; set; } = [];

    public DateTimeOffset CreatedAt { get; set; }

    public DateTimeOffset? UpdatedAt { get; set; }

    public Guid? UpdatedBy { get; set; }

    public short Version { get; set; }
}
